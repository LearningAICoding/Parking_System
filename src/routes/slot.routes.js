const express = require('express');
const { param } = require('express-validator');
const { requireAuth, authorizeRoles } = require('../middlewares/auth.middleware');
const { validateRequest } = require('../middlewares/validate.middleware');
const { verifyCsrf } = require('../middlewares/csrf.middleware');
const { viewLabels } = require('../middlewares/view-locals.middleware');
const asyncHandler = require('../utils/async-handler');
const controller = require('../controllers/slot.controller');
const router = express.Router();
const validId = [param('id').isInt({ min: 1 }), validateRequest];
router.use(viewLabels);
router.get('/slots', requireAuth, authorizeRoles('MANAGER', 'STAFF'), asyncHandler(controller.list));
router.get('/slots/create', requireAuth, authorizeRoles('MANAGER'), asyncHandler(controller.createForm));
router.post('/slots/create', requireAuth, authorizeRoles('MANAGER'), verifyCsrf, asyncHandler(controller.create));
router.get('/slots/:id/edit', requireAuth, authorizeRoles('MANAGER'), ...validId, asyncHandler(controller.editForm));
router.post('/slots/:id/edit', requireAuth, authorizeRoles('MANAGER'), verifyCsrf, ...validId, asyncHandler(controller.edit));
router.get('/slots/:id', requireAuth, authorizeRoles('MANAGER', 'STAFF'), ...validId, asyncHandler(controller.detail));
router.delete('/slots/:id', requireAuth, authorizeRoles('MANAGER'), verifyCsrf, ...validId, asyncHandler(controller.remove));
module.exports = router;
